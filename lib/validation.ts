import { z } from "zod";

/**
 * Validators for every user- or GitHub-controlled value that ends up in a URL,
 * a command argument, a sprite name or a branch name. Nothing that fails these
 * checks is ever passed on; values are also always passed as argv entries,
 * never concatenated into shell strings.
 */

/** GitHub login rules: alphanumerics and single hyphens, no leading/trailing hyphen, max 39. */
export const githubOwnerSchema = z
  .string()
  .regex(/^[A-Za-z0-9](?:[A-Za-z0-9]|-(?=[A-Za-z0-9])){0,38}$/, "Invalid GitHub owner");

/** GitHub repo names: letters, digits, '.', '-', '_'; not '.' or '..'; max 100. */
export const githubRepoNameSchema = z
  .string()
  .regex(/^[A-Za-z0-9._-]{1,100}$/, "Invalid GitHub repository name")
  .refine((name) => name !== "." && name !== ".." && !name.endsWith(".git"), "Invalid GitHub repository name");

export const repoRefSchema = z.object({
  owner: githubOwnerSchema,
  repo: githubRepoNameSchema,
});
export type RepoRef = z.infer<typeof repoRefSchema>;

export const issueNumberSchema = z.coerce
  .number({ error: "Issue number must be a number" })
  .int("Issue number must be an integer")
  .positive("Issue number must be positive")
  .max(2_147_483_647, "Issue number is too large");

export const issueRefSchema = repoRefSchema.extend({ issueNumber: issueNumberSchema });
export type IssueRef = z.infer<typeof issueRefSchema>;

/** Parse "owner/repo" into a validated RepoRef. */
export function parseRepoSlug(slug: string): RepoRef {
  const parts = slug.split("/");
  if (parts.length !== 2) throw new z.ZodError([{ code: "custom", message: "Expected owner/repo", path: [], input: slug }]);
  return repoRefSchema.parse({ owner: parts[0], repo: parts[1] });
}

export function repoSlug(ref: RepoRef): string {
  return `${ref.owner}/${ref.repo}`;
}

/**
 * Safe git branch names generated by Shipfig (we never accept arbitrary branch
 * names from users or issue text). Stricter than `git check-ref-format`.
 */
export const branchNameSchema = z
  .string()
  .min(1)
  .max(200)
  .regex(/^[A-Za-z0-9][A-Za-z0-9._/-]*$/, "Invalid branch name")
  .refine(
    (b) => !b.includes("..") && !b.includes("//") && !b.endsWith("/") && !b.endsWith(".") && !b.endsWith(".lock") && !b.includes("@{"),
    "Invalid branch name",
  );

/** Sprite names: lowercase alphanumerics and hyphens, max 63 (DNS label). */
export const spriteNameSchema = z.string().regex(/^[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?$/, "Invalid sprite name");

/**
 * Paths forwarded through the connector gateway. Must be an absolute API path
 * with no traversal, whitespace, control characters, fragments or scheme.
 */
export const gatewayPathSchema = z
  .string()
  .max(2048)
  .regex(/^\/[A-Za-z0-9._~\-/%]*$/, "Invalid gateway path")
  .refine((p) => !p.split("/").some((seg) => seg === ".." || seg === "."), "Gateway path must not contain dot segments")
  .refine((p) => !/%2e|%2f|%5c|%00/i.test(p), "Gateway path must not contain encoded separators");

/** Encode a single path segment after validating it is a safe identifier. */
export function pathSegment(value: string | number): string {
  const s = String(value);
  if (!/^[A-Za-z0-9._-]+$/.test(s) || s === "." || s === "..") {
    throw new Error(`Unsafe path segment: ${JSON.stringify(s)}`);
  }
  return s;
}
